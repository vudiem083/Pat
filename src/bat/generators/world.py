"""World toolkit: inspection, metadata editing with backups, pack bindings.

Safety rules:
  * every destructive edit writes a snapshot first (``runtime/snapshots/``),
  * ``level.dat`` is written atomically and re-read to verify the result,
  * pack bindings are derived from the project's actual packs, never invented,
  * BAT never claims chunk/terrain data it did not create.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

from ..core.errors import make_error
from ..core.models import Project, ProjectType
from ..core.nbt import NbtError, WorldMetadata, read_level_dat, unwrap, write_level_dat
from ..core.projects import ProjectManager
from ..core.models import utcnow
from ..storage.workspace import RuntimeLayout

GAMEMODES = {
    "survival": 0,
    "creative": 1,
    "adventure": 2,
    "spectator": 6,
}
GAMEMODE_NAMES = {v: k for k, v in GAMEMODES.items()}
DIFFICULTY_NAMES = {0: "peaceful", 1: "easy", 2: "normal", 3: "hard"}


class WorldGenerator:
    def __init__(self, projects: ProjectManager, layout: RuntimeLayout) -> None:
        self.projects = projects
        self.layout = layout

    # -- inspection --------------------------------------------------------
    def inspect(self, project_id: str) -> dict[str, Any]:
        project = self.projects.get(project_id)
        if ProjectType(project.project_type) not in (ProjectType.WORLD, ProjectType.COMBINED):
            raise make_error(
                "BAT-PROJECT-003",
                "This project has no world. WORLD and COMBINED projects own a world.",
                http_status=409,
            )
        world_dir = self.projects.ensure_world_dir(project_id)
        result: dict[str, Any] = {
            "project_id": project_id,
            "world_path": "world",
            "level_name": None,
            "metadata": None,
            "level_dat_status": "MISSING",
            "level_dat_error": None,
            "has_leveldb": (world_dir / "db").is_dir(),
            "leveldb_files": [],
            "behavior_packs": self._read_bindings(world_dir / "world_behavior_packs.json"),
            "resource_packs": self._read_bindings(world_dir / "world_resource_packs.json"),
            "notes": [],
        }
        level_dat = world_dir / "level.dat"
        if level_dat.exists():
            result["level_dat_bytes"] = level_dat.stat().st_size
            try:
                compound = unwrap(read_level_dat(level_dat))
                result["level_dat_status"] = "OK"
                result["metadata"] = compound
                result["level_name"] = compound.get("LevelName")
                game_type = compound.get("GameType")
                if isinstance(game_type, int):
                    result["game_mode"] = GAMEMODE_NAMES.get(game_type, f"unknown({game_type})")
                difficulty = compound.get("Difficulty")
                if isinstance(difficulty, int):
                    result["difficulty"] = DIFFICULTY_NAMES.get(difficulty, difficulty)
                result["storage_version"] = compound.pop("__storage_version", None)
            except (NbtError, FileNotFoundError) as exc:
                result["level_dat_status"] = "INVALID"
                result["level_dat_error"] = str(exc)
        else:
            result["level_dat_error"] = "level.dat is missing from the world directory."
        db_dir = world_dir / "db"
        if db_dir.is_dir():
            result["leveldb_files"] = sorted(p.name for p in db_dir.iterdir() if p.is_file())
            result["notes"].append(
                "Chunk data lives in a LevelDB store. BAT does not parse LevelDB chunks; "
                "use get_world_chunks for the honest level of detail available."
            )
        else:
            result["notes"].append(
                "No db/ directory: terrain is generated by Minecraft on first load. BAT does "
                "not fabricate chunk data."
            )
        return result

    @staticmethod
    def _read_bindings(path: Path) -> list[dict[str, Any]]:
        if not path.exists():
            return []
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            return []
        return data if isinstance(data, list) else []

    # -- chunk reporting ---------------------------------------------------
    def chunks(self, project_id: str) -> dict[str, Any]:
        world_dir = self.projects.ensure_world_dir(project_id)
        db_dir = world_dir / "db"
        files = (
            [p.name for p in sorted(db_dir.iterdir()) if p.is_file()] if db_dir.is_dir() else []
        )
        return {
            "project_id": project_id,
            "chunk_data_present": bool(files),
            "leveldb_files": files,
            "chunks": [],
            "chunk_count": None,
            "status": "NOT_TESTED" if not files else "UNKNOWN",
            "notes": (
                "BAT does not implement a LevelDB chunk reader. Reporting a chunk list would "
                "require parsing the world database, which BAT deliberately does not guess at. "
                "Use a Minecraft server load (start_runtime_job) to generate chunk data, then "
                "inspect the db/ files."
            ),
        }

    # -- safe metadata editing --------------------------------------------
    def snapshot(self, project: Project, reason: str) -> Path:
        """Copy the world into ``runtime/snapshots`` before a destructive edit."""
        world_dir = self.projects.ensure_world_dir(project.project_id)
        snapshot_id = f"snapshot_{utcnow().replace(':', '').replace('-', '')[:15]}_{project.project_id[:8]}"
        target = self.layout.snapshot_dir(snapshot_id)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(world_dir, target / "world")
        meta = {
            "snapshot_id": snapshot_id,
            "project_id": project.project_id,
            "reason": reason,
            "created_at": utcnow(),
            "source": "world",
        }
        (target / "snapshot.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
        return target

    def modify_metadata(
        self,
        project_id: str,
        *,
        level_name: str | None = None,
        game_mode: str | None = None,
        difficulty: str | int | None = None,
        seed: int | None = None,
        spawn: tuple[int, int, int] | list[int] | None = None,
        commands_enabled: bool | None = None,
    ) -> dict[str, Any]:
        project = self.projects.require_active(self.projects.get(project_id))
        world_dir = self.projects.ensure_world_dir(project_id)
        level_dat = world_dir / "level.dat"
        if not level_dat.exists():
            raise make_error(
                "BAT-WORLD-001",
                "Cannot modify metadata: level.dat is missing. Create the world files first.",
                http_status=409,
            )
        try:
            current = unwrap(read_level_dat(level_dat))
        except NbtError as exc:
            raise make_error("BAT-WORLD-001", f"level.dat is unreadable: {exc}") from exc

        snapshot = self.snapshot(project, "modify_world_metadata")

        metadata = WorldMetadata(
            level_name=level_name if level_name is not None else str(current.get("LevelName", project.name)),
            game_type=GAMEMODES.get(game_mode.lower(), int(current.get("GameType", 1)))
            if isinstance(game_mode, str)
            else int(current.get("GameType", 1)),
            difficulty=_difficulty_value(difficulty, int(current.get("Difficulty", 1))),
            seed=int(seed) if seed is not None else int(current.get("RandomSeed", 0)),
            spawn_x=int(spawn[0]) if spawn else int(current.get("SpawnX", 0)),
            spawn_y=int(spawn[1]) if spawn else int(current.get("SpawnY", 64)),
            spawn_z=int(spawn[2]) if spawn else int(current.get("SpawnZ", 0)),
            target_version=project.target_version,
            commands_enabled=(
                bool(commands_enabled)
                if commands_enabled is not None
                else bool(current.get("commandsEnabled", 1))
            ),
            time=int(current.get("Time", 0)),
        )
        if game_mode is not None and game_mode.lower() not in GAMEMODES:
            raise make_error(
                "BAT-INPUT-001",
                f"Unknown game_mode {game_mode!r}. Use one of {sorted(GAMEMODES)}.",
            )
        write_level_dat(level_dat, metadata)
        # Verify the write round-trips before declaring success.
        verified = unwrap(read_level_dat(level_dat))
        if verified.get("LevelName") != metadata.level_name:
            raise make_error(
                "BAT-WORLD-001",
                "level.dat verification failed after write; snapshot retained at "
                f"{snapshot}.",
            )
        if level_name is not None:
            (world_dir / "levelname.txt").write_text(metadata.level_name + "\n", encoding="utf-8")
        self.projects.touch(project)
        readback = unwrap(read_level_dat(level_dat))
        readback.pop("__storage_version", None)
        return {
            "project_id": project_id,
            "snapshot": str(snapshot),
            "verified": True,
            "metadata": readback,
            "game_mode": GAMEMODE_NAMES.get(metadata.game_type, metadata.game_type),
            "difficulty": DIFFICULTY_NAMES.get(metadata.difficulty, metadata.difficulty),
        }

    # -- pack bindings -----------------------------------------------------
    def bind_packs(self, project_id: str) -> dict[str, Any]:
        """Write world pack bindings from the packs that actually exist."""
        project = self.projects.require_active(self.projects.get(project_id))
        world_dir = self.projects.ensure_world_dir(project_id)
        packs = self.projects.list_packs(project_id)
        behavior: list[dict[str, Any]] = []
        resource: list[dict[str, Any]] = []
        skipped: list[str] = []
        for pack in packs:
            uuid_value = pack.get("header_uuid")
            if not uuid_value:
                skipped.append(pack["path"])
                continue
            entry = {"pack_id": uuid_value, "version": [1, 0, 0]}
            (behavior if pack["kind"] == "BEHAVIOR" else resource).append(entry)
        (world_dir / "world_behavior_packs.json").write_text(
            json.dumps(behavior, indent=2) + "\n", encoding="utf-8"
        )
        (world_dir / "world_resource_packs.json").write_text(
            json.dumps(resource, indent=2) + "\n", encoding="utf-8"
        )
        self.projects.touch(project)
        return {
            "project_id": project_id,
            "behavior_packs": behavior,
            "resource_packs": resource,
            "skipped_without_manifest_uuid": skipped,
        }

    # -- deletion ----------------------------------------------------------
    def delete_world_file(self, project_id: str, relative: str) -> dict[str, Any]:
        project = self.projects.require_active(self.projects.get(project_id))
        from ..core.filesystem import resolve_within

        world_dir = self.projects.ensure_world_dir(project_id)
        target = resolve_within(world_dir, relative, must_exist=True)
        if target.is_dir():
            raise make_error("BAT-INPUT-001", "Only individual world files can be deleted.")
        snapshot = self.snapshot(project, f"delete world file {relative}")
        target.unlink()
        self.projects.touch(project)
        return {"project_id": project_id, "deleted": relative, "snapshot": str(snapshot)}


def _difficulty_value(value: str | int | None, default: int) -> int:
    if value is None:
        return default
    if isinstance(value, int):
        if 0 <= value <= 3:
            return value
        raise make_error("BAT-INPUT-001", "difficulty must be 0-3 or peaceful/easy/normal/hard.")
    normalized = str(value).lower()
    mapping = {"peaceful": 0, "easy": 1, "normal": 2, "hard": 3}
    if normalized not in mapping:
        raise make_error("BAT-INPUT-001", "difficulty must be peaceful, easy, normal or hard.")
    return mapping[normalized]
