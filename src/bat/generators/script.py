"""Script module generation.

Adds a ``script`` module to the behavior pack manifest (plus the
``@minecraft/server`` dependency) and writes an entry script. BAT does not claim
the script runs correctly: without a real server the result is NOT_TESTED.
"""

from __future__ import annotations

import json
import uuid

from ..compatibility.script_api_registry import GENERATED_MODULES
from ..compatibility.versions import parse_version
from ..core.errors import make_error
from ..core.models import CompatibilityStatus, GeneratedFile, PackKind
from .common import GenerationContext

_MAIN_TEMPLATE = '''// Generated by BAT (Bedrock Agent Toolkit)
// Entry script for script module "{module_name}".
import {{ world, system }} from "@minecraft/server";

system.runInterval(() => {{
  const players = world.getAllPlayers();
  if (players.length === 0) return;
  for (const player of players) {{
    player.onScreenDisplay.setActionBar("{module_name} active");
  }}
}}, 120);

world.afterEvents.playerSpawn.subscribe((event) => {{
  if (!event.initialSpawn) return;
  event.player.sendMessage("Script module {module_name} loaded.");
}});
'''


def create_script_module(
    context: GenerationContext,
    *,
    module_name: str = "main",
    include_ui: bool = False,
) -> GeneratedFile:
    context.feature("manifest.script_module")
    cleaned = (module_name or "main").strip().replace(" ", "_")
    if not cleaned.replace("_", "").isalnum():
        raise make_error("BAT-INPUT-001", "Script module name must be alphanumeric/underscore.")
    pack = context.primary_pack(PackKind.BEHAVIOR)
    manifest_path = pack / "manifest.json"
    if not manifest_path.exists():
        raise make_error("BAT-MANIFEST-001", "Behavior pack manifest is missing.")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    modules = manifest.setdefault("modules", [])

    already = any(m.get("type") == "script" for m in modules if isinstance(m, dict))
    if not already:
        modules.append(
            {
                "type": "script",
                "language": "javascript",
                "uuid": str(uuid.uuid4()),
                "version": [1, 0, 0],
                "entry": f"scripts/{cleaned}.js",
            }
        )
        dependencies = manifest.setdefault("dependencies", [])
        server_module = GENERATED_MODULES[0]
        dependency = {
            "module_name": server_module.module,
            "version": server_module.api_version,
        }
        if include_ui:
            dependency = {
                "module_name": "@minecraft/server-ui",
                "version": GENERATED_MODULES[1].api_version,
            }
            if all(d.get("module_name") != dependency["module_name"] for d in dependencies):
                dependencies.append(dependency)
            dependency = {
                "module_name": server_module.module,
                "version": server_module.api_version,
            }
        if all(d.get("module_name") != dependency["module_name"] for d in dependencies):
            dependencies.append(dependency)
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    script_path = pack / "scripts" / f"{cleaned}.js"
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text(_MAIN_TEMPLATE.format(module_name=cleaned), encoding="utf-8")

    target = parse_version(context.project.target_version)
    warnings = [
        "Script execution is NOT_TESTED: it requires a running Bedrock server with "
        "script APIs enabled in the world.",
    ]
    if target < parse_version("1.19.70"):
        warnings.append(
            "Target is older than 1.19.70; stable script APIs are unavailable and experimental "
            "APIs must be enabled for the module to load."
        )
    context.touch()
    return GeneratedFile(
        path=script_path.relative_to(context.projects.files_root(context.project.project_id)).as_posix(),
        kind="script.module",
        pack=pack.name,
        description=f"Script module '{cleaned}' with manifest wiring",
        compatibility_status=CompatibilityStatus.NOT_TESTED,
        warnings=warnings,
    )
