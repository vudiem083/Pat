"""Project and workspace management.

Each project lives in ``<workspace>/projects/<project_id>/``:

    project.json         canonical Project record (mirrors the database row)
    files/               sandboxed content root used by read/write project file
      behavior_packs/<pack>/
      resource_packs/<pack>/
      world/             (WORLD and COMBINED projects)

Add-on generators, validators, builders and runtime installation all operate on
this layout, which is the single source of truth for project content.
"""

from __future__ import annotations

import json
import shutil
import uuid
from pathlib import Path
from typing import Any, Iterable

from ..compatibility.versions import parse_version, require_supported
from ..config import Settings
from .errors import make_error
from .filesystem import read_text_file, resolve_within, walk_files, write_text_file
from .models import (
    Project,
    ProjectStatus,
    ProjectTreeNode,
    ProjectType,
    PackKind,
    new_uuid,
    utcnow,
)
from .nbt import write_level_dat, WorldMetadata

_PROJECT_FILE = "project.json"
_FILES_DIR = "files"

GAMEMODES = {"survival": 0, "creative": 1, "adventure": 2, "spectator": 6}


class ProjectManager:
    """Creates, inspects and mutates projects on disk + in the database."""

    def __init__(self, settings: Settings, db: Any) -> None:
        self.settings = settings
        self.db = db

    # -- paths -------------------------------------------------------------
    def project_dir(self, project_id: str) -> Path:
        return self.settings.projects_root / project_id

    def files_root(self, project_id: str) -> Path:
        return self.project_dir(project_id) / _FILES_DIR

    # -- creation ----------------------------------------------------------
    def create(
        self,
        *,
        name: str,
        project_type: ProjectType | str,
        target_version: str,
        description: str | None = None,
        world_name: str | None = None,
    ) -> Project:
        name = (name or "").strip()
        if not name:
            raise make_error("BAT-INPUT-001", "Project name must not be empty.")
        if len(name) > 120:
            raise make_error("BAT-INPUT-001", "Project name must be 120 characters or fewer.")
        try:
            ptype = ProjectType(project_type)
        except ValueError as exc:
            raise make_error(
                "BAT-PROJECT-001",
                f"Unsupported project type {project_type!r}. Use ADDON, WORLD or COMBINED.",
                details={"project_type": str(project_type)},
            ) from exc
        version = require_supported(target_version)
        if self.db.find_project_by_name(name) is not None:
            raise make_error(
                "BAT-PROJECT-002",
                f"A project named {name!r} already exists.",
                http_status=409,
            )

        project = Project(
            project_id=new_uuid(),
            name=name,
            project_type=ptype,
            target_version=version.short,
            description=description,
        )
        root = self.files_root(project.project_id)
        (root / "behavior_packs").mkdir(parents=True, exist_ok=True)
        (root / "resource_packs").mkdir(parents=True, exist_ok=True)

        if ptype in (ProjectType.ADDON, ProjectType.COMBINED):
            slug = _slug(name)
            project.pack_uuids[f"bp:{slug}"] = str(uuid.uuid4())
            project.pack_uuids[f"rp:{slug}"] = str(uuid.uuid4())
            self._seed_pack(project, PackKind.BEHAVIOR, slug)
            self._seed_pack(project, PackKind.RESOURCE, slug)

        if ptype in (ProjectType.WORLD, ProjectType.COMBINED):
            self._seed_world(project, world_name or name)

        self.db.save_project(project)
        self._persist_project_file(project)
        return project

    def _seed_pack(self, project: Project, kind: PackKind, slug: str) -> None:
        pack_dir = self.pack_dir(project.project_id, kind, slug)
        pack_dir.mkdir(parents=True, exist_ok=True)
        manifest = self.build_manifest(project, kind, slug)
        (pack_dir / "manifest.json").write_text(
            json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
        )
        if kind is PackKind.BEHAVIOR:
            (pack_dir / "entities").mkdir(exist_ok=True)
            (pack_dir / "items").mkdir(exist_ok=True)
            (pack_dir / "blocks").mkdir(exist_ok=True)
            (pack_dir / "recipes").mkdir(exist_ok=True)
        else:
            (pack_dir / "textures").mkdir(exist_ok=True)
            (pack_dir / "texts").mkdir(exist_ok=True)
            (pack_dir / "texts" / "en_US.lang").write_text(
                f"pack.name={project.name}\npack.description=Generated by BAT\n",
                encoding="utf-8",
            )

    def _seed_world(self, project: Project, world_name: str) -> None:
        world_dir = self.world_dir(project.project_id)
        (world_dir / "db").mkdir(parents=True, exist_ok=True)
        (world_dir / "levelname.txt").write_text(world_name + "\n", encoding="utf-8")
        metadata = WorldMetadata(
            level_name=world_name,
            game_type=1,
            difficulty=1,
            seed=0,
            spawn_x=0,
            spawn_y=64,
            spawn_z=0,
            target_version=project.target_version,
            generated_by="BAT",
        )
        write_level_dat(world_dir / "level.dat", metadata)
        (world_dir / "world_behavior_packs.json").write_text("[]\n", encoding="utf-8")
        (world_dir / "world_resource_packs.json").write_text("[]\n", encoding="utf-8")

    # -- manifests ---------------------------------------------------------
    def build_manifest(
        self, project: Project, kind: PackKind, slug: str, *, script_module: bool = False
    ) -> dict[str, Any]:
        key = f"{'bp' if kind is PackKind.BEHAVIOR else 'rp'}:{slug}"
        header_uuid = project.pack_uuids.get(key) or str(uuid.uuid4())
        project.pack_uuids[key] = header_uuid
        version = parse_version(project.target_version)
        modules: list[dict[str, Any]] = [
            {
                "type": "data" if kind is PackKind.BEHAVIOR else "resources",
                "uuid": str(uuid.uuid4()),
                "version": [1, 0, 0],
            }
        ]
        kind_label = "Behavior Pack" if kind is PackKind.BEHAVIOR else "Resource Pack"
        return {
            "format_version": 2,
            "header": {
                "name": f"{project.name} {kind_label}",
                "description": f"{kind_label} generated by BAT for {project.name}",
                "uuid": header_uuid,
                "version": [1, 0, 0],
                "min_engine_version": list(version.parts[:3]),
            },
            "modules": modules,
        }

    # -- lookup ------------------------------------------------------------
    def get(self, project_id: str) -> Project:
        project = self.db.get_project(project_id)
        if project is None:
            raise make_error(
                "BAT-NOTFOUND-001",
                f"Project {project_id} was not found.",
                details={"project_id": project_id},
                http_status=404,
            )
        return project

    def list(self, limit: int = 100, offset: int = 0) -> list[Project]:
        return self.db.list_projects(limit=limit, offset=offset)

    def require_active(self, project: Project) -> Project:
        if ProjectStatus(project.status) is ProjectStatus.ARCHIVED:
            raise make_error(
                "BAT-PROJECT-004",
                f"Project {project.name!r} is archived and cannot be modified.",
                http_status=409,
            )
        return project

    def touch(self, project: Project) -> Project:
        project.updated_at = utcnow()
        self.db.save_project(project)
        self._persist_project_file(project)
        return project

    def _persist_project_file(self, project: Project) -> None:
        target = self.project_dir(project.project_id) / _PROJECT_FILE
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(project.model_dump_json(indent=2) + "\n", encoding="utf-8")

    # -- pack helpers ------------------------------------------------------
    def pack_dir(self, project_id: str, kind: PackKind, slug: str) -> Path:
        base = "behavior_packs" if kind is PackKind.BEHAVIOR else "resource_packs"
        return self.files_root(project_id) / base / slug

    def list_packs(self, project_id: str) -> list[dict[str, Any]]:
        result: list[dict[str, Any]] = []
        for kind, base in (
            (PackKind.BEHAVIOR, "behavior_packs"),
            (PackKind.RESOURCE, "resource_packs"),
        ):
            directory = self.files_root(project_id) / base
            if not directory.exists():
                continue
            for pack in sorted(p for p in directory.iterdir() if p.is_dir()):
                manifest_path = pack / "manifest.json"
                manifest: dict[str, Any] | None = None
                error: str | None = None
                if manifest_path.exists():
                    try:
                        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
                    except json.JSONDecodeError as exc:
                        error = str(exc)
                result.append(
                    {
                        "kind": kind.value,
                        "slug": pack.name,
                        "path": f"{base}/{pack.name}",
                        "has_manifest": manifest is not None,
                        "manifest_error": error,
                        "header_uuid": (manifest or {}).get("header", {}).get("uuid"),
                        "header_name": (manifest or {}).get("header", {}).get("name"),
                    }
                )
        return result

    def world_dir(self, project_id: str) -> Path:
        return self.files_root(project_id) / "world"

    def ensure_world_dir(self, project_id: str) -> Path:
        directory = self.world_dir(project_id)
        if not directory.exists():
            raise make_error(
                "BAT-PROJECT-003",
                "This project has no world. WORLD and COMBINED projects own a world.",
                http_status=409,
            )
        return directory

    # -- tree --------------------------------------------------------------
    def tree(self, project_id: str, *, max_entries: int = 2000) -> ProjectTreeNode:
        self.get(project_id)
        root = self.files_root(project_id)
        counter = {"n": 0}

        def build(path: Path) -> ProjectTreeNode:
            rel = path.relative_to(root).as_posix() if path != root else "."
            if path.is_dir():
                children: list[ProjectTreeNode] = []
                if counter["n"] < max_entries:
                    for child in sorted(
                        (c for c in path.iterdir() if not c.name.startswith(".")),
                        key=lambda c: (c.is_file(), c.name),
                    ):
                        if counter["n"] >= max_entries:
                            break
                        counter["n"] += 1
                        children.append(build(child))
                return ProjectTreeNode(name=path.name or "files", path=rel, type="dir", children=children)
            return ProjectTreeNode(
                name=path.name, path=rel, type="file", size=path.stat().st_size
            )

        return build(root)

    # -- file IO -----------------------------------------------------------
    def resolve_file(self, project_id: str, relative_path: str) -> Path:
        self.get(project_id)
        return resolve_within(self.files_root(project_id), relative_path)

    def read_file(self, project_id: str, relative_path: str) -> dict[str, Any]:
        path = self.resolve_file(project_id, relative_path)
        content = read_text_file(path, max_bytes=self.settings.max_file_bytes)
        rel = path.resolve().relative_to(self.files_root(project_id).resolve()).as_posix()
        return {
            "project_id": project_id,
            "path": rel,
            "content": content,
            "size_bytes": len(content.encode("utf-8")),
        }

    def write_file(
        self,
        project_id: str,
        relative_path: str,
        content: str,
        *,
        create_backup: bool = True,
    ) -> dict[str, Any]:
        project = self.require_active(self.get(project_id))
        path = self.resolve_file(project_id, relative_path)
        backup: str | None = None
        existed = path.exists()
        if existed and create_backup:
            backup_path = path.with_suffix(path.suffix + ".bak")
            shutil.copy2(path, backup_path)
            backup = backup_path.resolve().relative_to(
                self.files_root(project_id).resolve()
            ).as_posix()
        size = write_text_file(path, content, max_bytes=self.settings.max_file_bytes)
        self.touch(project)
        rel = path.resolve().relative_to(self.files_root(project_id).resolve()).as_posix()
        return {
            "project_id": project_id,
            "path": rel,
            "size_bytes": size,
            "created": not existed,
            "backup": backup,
        }

    def delete_file(self, project_id: str, relative_path: str) -> dict[str, Any]:
        project = self.require_active(self.get(project_id))
        path = self.resolve_file(project_id, relative_path)
        if not path.exists():
            raise make_error("BAT-NOTFOUND-002", f"File not found: {relative_path}", http_status=404)
        if path.is_dir():
            raise make_error("BAT-INPUT-001", "delete_project_file only deletes files.")
        path.unlink()
        self.touch(project)
        return {"project_id": project_id, "path": relative_path, "deleted": True}

    def iter_files(self, project_id: str) -> Iterable[Path]:
        self.get(project_id)
        return walk_files(self.files_root(project_id))

    # -- deletion ----------------------------------------------------------
    def delete(self, project_id: str, *, purge_artifacts: bool = False) -> dict[str, Any]:
        """Delete a project's files and record.

        Runtime incidents and session evidence are intentionally kept: destroying
        a project must not destroy diagnostic history. Artifacts are kept unless
        ``purge_artifacts`` is explicitly requested.
        """
        project = self.get(project_id)
        root = self.project_dir(project_id)
        removed = False
        if root.exists():
            shutil.rmtree(root)
            removed = True
        self.db.delete_project(project_id)
        purged = 0
        if purge_artifacts:
            artifact_root = self.settings.artifacts_root / project_id
            if artifact_root.exists():
                purged = sum(1 for _ in artifact_root.rglob("*") if _.is_file())
                shutil.rmtree(artifact_root)
        return {
            "project_id": project_id,
            "name": project.name,
            "removed_files": removed,
            "artifacts_purged": purged,
            "retained": {
                "incidents": "kept (diagnostic evidence is never deleted with a project)",
                "sessions": "kept under the runtime sessions directory",
                "artifacts": "kept" if not purge_artifacts else "purged",
            },
        }


def _slug(name: str) -> str:
    cleaned = "".join(c if c.isalnum() or c in "-_" else "_" for c in name.strip().lower())
    cleaned = "_".join(filter(None, cleaned.split("_")))
    return (cleaned or "pack")[:48]
