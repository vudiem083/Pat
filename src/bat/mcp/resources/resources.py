"""MCP resources exposing live BAT knowledge and project state.

Resources return real data generated from the compatibility registries and the
project store — never hardcoded placeholders.
"""

from __future__ import annotations

import json
from typing import Any

from ...compatibility.component_registry import COMPONENTS
from ...compatibility.feature_matrix import matrix_report
from ...compatibility.script_api_registry import module_records, script_api_status
from ...services import BatServices
from ...version import SUPPORTED_VERSION_MAX, SUPPORTED_VERSION_MIN, __version__


def register(mcp: Any, services: BatServices) -> None:
    @mcp.resource("bat://docs/bedrock/versions")
    def versions_doc() -> str:
        """Supported Bedrock versions and the feature matrix for the newest target."""
        payload = {
            "supported_range": {"min": SUPPORTED_VERSION_MIN, "max": SUPPORTED_VERSION_MAX},
            "edition": "Bedrock (Minecraft PE is in scope; Java is out of scope)",
            "profiles": services.list_profiles(),
            "matrix": matrix_report(SUPPORTED_VERSION_MAX),
            "notes": [
                "Compatibility is version-aware. UNKNOWN means no evidence, not 'probably fine'.",
                "BAT never upgrades a project's target version implicitly.",
            ],
        }
        return json.dumps(payload, indent=2)

    @mcp.resource("bat://docs/bedrock/manifest")
    def manifest_doc() -> str:
        """Manifest requirements BAT enforces, plus a working example."""
        payload = {
            "requirements": {
                "format_version": "1 or 2 (BAT writes 2)",
                "header": ["name", "description", "uuid", "version", "min_engine_version"],
                "modules": "at least one; data/resources/script; unique UUIDs",
                "dependencies": "optional list; script modules need @minecraft/server",
            },
            "example": {
                "format_version": 2,
                "header": {
                    "name": "Example Behavior Pack",
                    "description": "Generated by BAT",
                    "uuid": "00000000-0000-0000-0000-000000000000",
                    "version": [1, 0, 0],
                    "min_engine_version": [1, 21, 0],
                },
                "modules": [
                    {"type": "data", "uuid": "11111111-1111-1111-1111-111111111111", "version": [1, 0, 0]}
                ],
            },
            "validated_by": "validate_manifest / validate_project",
        }
        return json.dumps(payload, indent=2)

    @mcp.resource("bat://docs/bedrock/entities")
    def entities_doc() -> str:
        """Entity document shape and the components BAT knows about."""
        components = [c for c in COMPONENTS if c.kind == "entity"]
        payload = {
            "format": {
                "format_version": "target series, e.g. 1.21.0",
                "minecraft:entity.description.identifier": "namespace:name",
                "minecraft:entity.components": "component map",
            },
            "known_components": [
                {"name": c.name, "min_version": c.min_version} for c in components
            ],
            "notes": [
                "Components absent from the registry are reported as UNKNOWN, not rejected.",
                "BAT validates structure; behaviour requires a runtime test.",
            ],
        }
        return json.dumps(payload, indent=2)

    @mcp.resource("bat://docs/bedrock/blocks")
    def blocks_doc() -> str:
        """Block document shape, components and texture expectations."""
        payload = {
            "shape": {
                "minecraft:block.description.identifier": "namespace:name",
                "minecraft:block.components": [
                    "minecraft:geometry",
                    "minecraft:material_instances",
                    "minecraft:destructible_by_mining",
                    "minecraft:destructible_by_explosion",
                ],
            },
            "known_components": [
                {"name": c.name, "min_version": c.min_version}
                for c in COMPONENTS
                if c.kind == "block"
            ],
            "textures": "material_instances textures must exist as PNG files in a resource pack.",
        }
        return json.dumps(payload, indent=2)

    @mcp.resource("bat://docs/bedrock/items")
    def items_doc() -> str:
        """Component-based item format requirements (Bedrock 1.20.50+)."""
        payload = {
            "minimum_version": "1.20.50",
            "shape": {
                "minecraft:item.description.identifier": "namespace:name",
                "minecraft:item.components": ["minecraft:icon", "minecraft:max_stack_size"],
            },
            "legacy_format": "Pre-1.20.50 item format is not generated by BAT; it is reported "
            "as UNSUPPORTED for that target instead of emitting unverifiable content.",
            "known_components": [
                {"name": c.name, "min_version": c.min_version}
                for c in COMPONENTS
                if c.kind == "item"
            ],
        }
        return json.dumps(payload, indent=2)

    @mcp.resource("bat://docs/bedrock/scripts")
    def scripts_doc() -> str:
        """Script module wiring and what BAT can/cannot verify."""
        payload = {
            "modules_written": module_records(),
            "stable_api_from": "1.19.70",
            "status_now": script_api_status(SUPPORTED_VERSION_MAX).value,
            "manifest_requirements": [
                "modules[] entry with type=script, language=javascript, entry=scripts/<name>.js",
                "dependencies[] entry for @minecraft/server",
            ],
            "limitations": [
                "Script execution is NOT_TESTED without a running server.",
                "BAT does not pin minor API versions per game release; it writes the stable floor.",
            ],
        }
        return json.dumps(payload, indent=2)

    @mcp.resource("bat://docs/bedrock/worlds")
    def worlds_doc() -> str:
        """World layout, level.dat format and BAT's editing guarantees."""
        payload = {
            "layout": ["level.dat", "levelname.txt", "db/", "world_behavior_packs.json", "world_resource_packs.json"],
            "level_dat": "uncompressed little-endian NBT with an 8-byte header (version, length)",
            "bat_guarantees": [
                "Snapshots are written before destructive metadata edits.",
                "level.dat writes are verified by re-reading the file.",
                "Chunk/terrain data is generated by Minecraft, never faked by BAT.",
                "Pack bindings are derived from the project's real packs.",
            ],
            "limitations": [
                "BAT has no LevelDB chunk reader; get_world_chunks reports that honestly.",
            ],
        }
        return json.dumps(payload, indent=2)

    @mcp.resource("bat://projects/{project_id}/tree")
    def project_tree(project_id: str) -> str:
        """Live file tree for a project."""
        return json.dumps(services.project_tree(project_id), indent=2)

    @mcp.resource("bat://projects/{project_id}/report")
    def project_report(project_id: str) -> str:
        """Latest validation report plus artifact and incident summary for a project."""
        project = services.projects.get(project_id)
        try:
            report = services.validator.latest_report(project_id).model_dump()
        except Exception:  # noqa: BLE001 - no report yet is a normal state
            report = None
        incidents = services.incidents.list(project_id=project_id, limit=10)
        artifacts = services.builders.list_artifacts(project_id)
        payload = {
            "project": project.model_dump(),
            "validation_report": report,
            "artifacts": artifacts,
            "incidents": [
                {
                    "incident_id": i.incident_id,
                    "type": i.incident_type,
                    "summary": i.summary,
                    "status": i.diagnostic_status,
                    "confidence": i.confidence,
                }
                for i in incidents
            ],
            "bat_version": __version__,
        }
        return json.dumps(payload, indent=2)
