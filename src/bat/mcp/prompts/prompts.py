"""MCP prompt templates that encode BAT's working method."""

from __future__ import annotations

from typing import Any

from ...services import BatServices
from ...version import SUPPORTED_VERSION_MAX, SUPPORTED_VERSION_MIN

_PREAMBLE = """You are working with BAT (Bedrock Agent Toolkit) for Minecraft Bedrock Edition
{supported_min}-{supported_max}. BAT exposes MCP tools for projects, add-ons, worlds,
validation, builds, jobs and runtime diagnostics.

Ground rules:
- Call tools, do not guess file contents or compatibility.
- Every tool returns {{"ok": true, "result": ...}} or {{"ok": false, "error": {{"error_code", "message"}}}}.
- Treat UNKNOWN / NOT_TESTED as unknown. Never claim a runtime test passed unless a tool says PASS.
- Project file paths are relative to the project files root.
""".replace("{supported_min}", SUPPORTED_VERSION_MIN).replace(
    "{supported_max}", SUPPORTED_VERSION_MAX
)


def register(mcp: Any, services: BatServices) -> None:
    @mcp.prompt(title="Create an add-on")
    def create_addon_prompt(
        description: str = "a simple add-on",
        target_version: str = "1.21.80",
    ) -> str:
        """Plan and build a Bedrock add-on with validation and an artifact."""
        return f"""{_PREAMBLE}
Task: create a Bedrock add-on for: {description}
Target version: {target_version}.

Steps:
1. get_compatibility({target_version}) and note anything UNSUPPORTED for this target.
2. create_project(name=..., project_type="ADDON", target_version="{target_version}").
3. Generate only the content the request needs (create_entity / create_block / create_item /
   create_recipe / create_loot_table / create_spawn_rule / ...). Items require 1.20.50+.
4. validate_project(project_id). Fix every ERROR; explain remaining WARNINGs.
5. build_project(project_id) and confirm each artifact reports integrity_ok=true.
6. Report: what was generated, validation status, artifact ids/checksums, and what is NOT_TESTED.
"""

    @mcp.prompt(title="Create a world")
    def create_world_prompt(name: str = "My World", target_version: str = "1.21.80") -> str:
        """Plan and build a Bedrock world (optionally combined with add-on packs)."""
        return f"""{_PREAMBLE}
Task: create a Bedrock world named "{name}" targeting {target_version}.

Steps:
1. create_world_project(name="{name}", target_version="{target_version}", include_addon=<true|false>).
2. If add-on packs are needed, create content, then bind_world_packs so the world references them.
3. modify_world_metadata to set game_mode / difficulty / spawn / level_name. A snapshot is
   created automatically; keep it until the operator confirms the change.
4. validate_world, then build_mcworld / export_mcworld and inspect the artifact.
5. State clearly that terrain/chunks are generated by Minecraft on first load, and that a
   .mcworld exported before any load contains no chunk data.
"""

    @mcp.prompt(title="Debug an add-on")
    def debug_addon_prompt(project_id: str, symptom: str = "the add-on does not work") -> str:
        """Systematically debug an add-on using validation, runtime and incidents."""
        return f"""{_PREAMBLE}
Project: {project_id}
Symptom: {symptom}

Work in evidence order:
1. get_project + get_project_tree: confirm which packs and files exist.
2. validate_project: collect error_codes and findings (file + line).
3. Fix the highest-severity findings with write_project_file, then re-validate.
4. If validation is clean, run_game_test(project_id) and poll get_job_status until terminal.
5. On failure, read get_job_report, get_runtime_logs(kind="errors"), then get_incidents(project_id)
   and get_incident_details. Quote evidence; if the diagnosis says the root cause is unknown,
   say so and propose the next experiment instead of inventing a cause.
"""

    @mcp.prompt(title="Fix validation errors")
    def fix_validation_errors_prompt(project_id: str) -> str:
        """Repair a project until validation passes without weakening the checks."""
        return f"""{_PREAMBLE}
Project: {project_id}

1. Call validate_project and list every ERROR with its code and file path.
2. For each error, read the file (read_project_file) and fix the actual cause with
   write_project_file. Do not delete files or disable checks to make the report green.
3. Re-run validate_project after each batch of fixes until status is PASS (or only WARNINGs
   remain, each of which you explain).
4. Summarise: errors fixed, warnings accepted and why, and any remaining UNKNOWN compatibility.
"""

    @mcp.prompt(title="Analyze runtime logs")
    def analyze_runtime_logs_prompt(session_id: str) -> str:
        """Analyse a runtime session's logs and produce an evidence-based diagnosis."""
        return f"""{_PREAMBLE}
Session: {session_id}

1. get_runtime_status({session_id}) and get_runtime_heartbeat({session_id}).
2. get_runtime_logs({session_id}, kind="errors", tail=200) and kind="console".
3. get_runtime_report({session_id}) for the structured log scan.
4. get_incidents(session_id="{session_id}") and get_incident_details for each incident.
5. Report: the exact evidence lines, the matched diagnostic code(s), possible causes with
   confidence, and concrete next actions. If evidence is insufficient, say the root cause is
   UNKNOWN and name the additional evidence you need.
"""
